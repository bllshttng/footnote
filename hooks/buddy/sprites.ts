// The fidget loop Claude Code's buddy used: rest, fidget, blink (-1), rest.
export const IDLE_SEQUENCE = [0, 0, 0, 0, 1, 0, 0, 0, -1, 0, 0, 2, 0, 0, 0]

export function renderSprite(bones: Bones, frame = 0): string[] {
  const frames = BODIES[bones.species]
  const lines = frames[Math.max(0, frame) % frames.length]!.map(line => {
    const drawn = line.replaceAll('{E}', bones.eye)
    return frame < 0 ? drawn.replaceAll(bones.eye, '-') : drawn
  })
  if (bones.hat !== 'none' && !lines[0]!.trim()) lines[0] = HAT_LINES[bones.hat]
  if (!lines[0]!.trim() && frames.every(f => !f[0]!.trim())) lines.shift()
  return lines
}

