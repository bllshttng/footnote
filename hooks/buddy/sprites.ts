  octopus: '~({E}{E})~', owl: '({E})({E})', penguin: '({E}>)', turtle: '[{E}_{E}]',
  snail: '{E}(@)', ghost: '/{E}{E}\\', axolotl: '}{E}.{E}{', capybara: '({E}oo{E})',
  cactus: '|{E}  {E}|', robot: '[{E}{E}]', rabbit: '({E}..{E})', mushroom: '|{E}  {E}|', chonk: '({E}.{E})',
